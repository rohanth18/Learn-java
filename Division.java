public interface Division 
{
    public static void main(String[] args) {
        
    
    int num1=5;
    int num2=2;
    System.out.println("Using variable");
    System.out.println("Integer division: "+(num1/num2));
    System.out.println("Floating division: "+((float)num1/num2));

    System.out.println();
    System.out.println("Without using variables");
    System.out.println("Integer Division: "+(5/2));
    System.out.println("Floating Division: "+(5.067387293898287/2));
    }  
}
