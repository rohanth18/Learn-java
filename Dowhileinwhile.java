public class Dowhileinwhile 
{
    public static void main(String[] args) 
    {
        int i=1;
        while(i<=3)
        {
            int j=1;
            do{
                
                System.out.print(j);
                j++;
            }while(j<=3);
            i++;
            System.out.println();
        }
        
    }
    
}
