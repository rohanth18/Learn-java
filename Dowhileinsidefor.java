public class Dowhileinsidefor 
{
    public static void main(String[] args) 
    {
        for(int i=1;i<=3;i++)
        {
            int j=1;
            do{
                System.out.print(j);
                j++;
            }while(j<=3);
            System.out.println();
        }
        
    }
    
}
